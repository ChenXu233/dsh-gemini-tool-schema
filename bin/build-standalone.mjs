#!/usr/bin/env node
/**
 * build-standalone.mjs — emit a single-file, dependency-free ESM bundle.
 *
 * Why: DSH's config HMR re-mounts a plugin but Node's ESM cache never
 * re-evaluates an already-imported URL. Writing each build to a NEW path lets
 * a running harness pick up code changes without a restart.
 *
 * Usage: node bin/build-standalone.mjs [outfile]
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(process.argv[2] ?? resolve(here, '../dist/dsh-tool-schema-compat.mjs'));

const stripExports = (source) => source
  .replace(/^export function /gm, 'function ')
  .replace(/^export const /gm, 'const ')
  .replace(/^export \{[^}]*\};?$/gm, '');

const normalize = stripExports(readFileSync(resolve(here, '../src/normalize.mjs'), 'utf8'));
const plugin = readFileSync(resolve(here, '../src/index.mjs'), 'utf8')
  .replace(/^import \{[^}]*\} from '\.\/normalize\.mjs';?$/gm, '')
  .replace(/^export \{[^}]*\} from '\.\/normalize\.mjs';?$/gm, '');

const bundle = [
  '/* generated by bin/build-standalone.mjs — do not edit; edit src/ instead */',
  normalize,
  '// ------------------------------ plugin ------------------------------',
  plugin,
].join('\n\n');

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, bundle);
console.log('wrote ' + out + ' (' + bundle.length + ' bytes)');
